/**
 * A function to recursively purge a directory
 *
 * @param string $dir The directory path.
 */
function nfd_sm_delete_directory( $dir ) {
	if ( ! is_dir( $dir ) ) {
		return false;
	}

	$files = scandir( $dir );
	foreach ( $files as $file ) {
		if ( '.' !== $file && '..' !== $file ) {
			$path = $dir . '/' . $file;
			if ( is_dir( $path ) ) {
				nfd_sm_delete_directory( $path ); // Recursively delete subdirectories
			} else {
				unlink( $path ); // Delete individual files
			}
		}
	}

	return rmdir( $dir ); // Remove the empty directory
}

/**
 * Whether an import is under way, or finished and still awaiting a decision.
 *
 * The thing this protects is the ability to undo. A finished-but-undecided run's `nfdold_` backup
 * tables are the only copy of this site as it was, and `Importer::rollback()` reads the checkpoint
 * on disk to know what to put back -- so deleting the state directory leaves the tables orphaned
 * and the site with no way to return to itself. A run still in flight is worse: it may be one
 * statement short of the swap.
 *
 * Deliberately narrow. A source that has merely exported has a package and nothing at stake in the
 * database; deleting a plugin is a deliberate act and taking its files with it is what deleting
 * means. Being unable to reverse a migration is a different order of loss.
 *
 * @return bool
 */
function nfd_sm_import_unsettled() {
	if ( ! class_exists( '\\NewfoldLabs\\WP\\SiteMigrator\\Core\\Import\\ImportCheckpoint' ) ) {
		return false;
	}

	$checkpoint = new \NewfoldLabs\WP\SiteMigrator\Core\Import\ImportCheckpoint();

	if ( ! $checkpoint->exists() ) {
		return false;
	}

	return ! \NewfoldLabs\WP\SiteMigrator\Core\Import\ImportCheckpoint::is_settled( $checkpoint->load() );
}

/**
 * Forget what a reactivation can work out again.
 *
 * This is all deactivation does, and the restraint is the point. It used to run
 * `nfd_sm_purge_all()`, which recursively deletes the storage directory -- so switching the plugin
 * off to check whether it was causing something destroyed the package the user had just spent an
 * hour building, with no warning and nothing to undo it. Deactivating is the routine "turn
 * everything off and find the conflict" move; WordPress asks a plugin to make it reversible, and
 * removing data belongs in `uninstall.php`.
 *
 * The worse case was a destination mid-import. The same call deleted `import/`, and with it the
 * checkpoint `Importer::rollback()` needs -- leaving a swapped site, orphaned backup tables, and
 * no way for the plugin to put it back.
 *
 * @return void
 */
function nfd_sm_flush_state() {
	delete_transient( NFD_SM_CAN_MIGRATE_TRANSIENT );
}

/**
 * Everything deleting this plugin should take with it.
 *
 * Split out of `uninstall.php` so it can be tested, and so the multisite branch below has
 * somewhere to live that is not a bare script.
 *
 * **On a network, every site has its own.** `wp_get_upload_dir()` follows `switch_to_blog()`, so a
 * network-activated plugin leaves a storage directory and an options row on each site rather than
 * one of each on the network. Migration itself is blocked at preflight on multisite, so what is
 * left behind is an empty protected directory and a row of defaults — small, but leftover data is
 * leftover data, and the same loop that removes it is the loop that would remove a real package if
 * multisite ever becomes supported.
 *
 * A large network is skipped rather than iterated. WordPress stops counting sites past
 * `wp_is_large_network()` for the same reason this stops deleting past it: a loop long enough to
 * exhaust the request leaves the uninstall half-done, and a half-purged network is worse than an
 * untouched one. On such a network the directories can be removed with `wp site-migrator` gone and
 * a filesystem sweep, which is a thing an administrator of ten thousand sites can do and a plugin
 * being deleted cannot.
 *
 * @return void
 */
function nfd_sm_uninstall() {
	if ( ! is_multisite() ) {
		if ( ! nfd_sm_import_unsettled() ) {
			nfd_sm_purge_all();
		}

		return;
	}

	if ( wp_is_large_network( 'sites' ) ) {
		return;
	}

	// `number => 0` is load-bearing. `WP_Site_Query` defaults to **100**, so the obvious call
	// purges the first hundred sites of a network and leaves the rest -- which is precisely the
	// half-purged state the guard above exists to avoid, arrived at by a default rather than by a
	// timeout. Any network between 101 sites and `wp_is_large_network()` hits it.
	$sites = get_sites(
		array(
			'fields' => 'ids',
			'number' => 0,
		)
	);

	foreach ( $sites as $site_id ) {
		switch_to_blog( (int) $site_id );

		try {
			// Asked per site, because the answer is per site: the checkpoint lives under that
			// site's own uploads directory.
			if ( ! nfd_sm_import_unsettled() ) {
				nfd_sm_purge_all();
			}
		} finally {
			// A network left switched to the wrong site is a strange thing to hand back to
			// whatever runs next, and one throw from a future change is all it would take.
			restore_current_blog();
		}
	}
}

/**
 * Purge Migration related things
 */
function nfd_sm_purge_all() {
	// Delete the options
	foreach ( NFD_SM_OPTIONS_LIST as $option ) {
		delete_option( $option );
	}

	// Delete the migration data
	nfd_sm_delete_directory( nfd_sm_storage_path() );

	// Delete the transient
	delete_transient( NFD_SM_CAN_MIGRATE_TRANSIENT );
}

/**
 * Express a path relative to a root directory, with forward slashes.
 *
 * @param string $root Absolute root directory.
 * @param string $path Absolute path inside the root.
 *
 * @return string Relative path, or the basename when $path is not below $root.
 */
function nfd_sm_relative_path( $root, $path ) {
	$root = rtrim( str_replace( '\\', '/', $root ), '/' ) . '/';
	$path = str_replace( '\\', '/', $path );

	if ( 0 === strpos( $path, $root ) ) {
		return substr( $path, strlen( $root ) );
	}

	return basename( $path );
}

/**
 * Absolute path to this plugin's main file, with symlinks resolved.
 *
 * @return string
 */
function nfd_sm_plugin_file() {
	return NFD_SM_PLUGIN_DIR . NFD_SM_PLUGIN_NAME . '.php';
}

/**
 * How WordPress addresses this plugin in `active_plugins`: `directory/file.php`.
 *
 * Not `NFD_SM_PLUGIN_NAME . '/' . NFD_SM_PLUGIN_NAME . '.php'`, which is a guess that is wrong
 * whenever the directory is not named after the slug — a checkout under its repository name, a
 * Composer or Bedrock deployment, or a symlink into a working copy. Writing the guess into
 * `active_plugins` activates nothing, because there is no file at that path; `Fixups` then
 * deactivates it again as missing, and the plugin is left loaded only by the import loader, at
 * which point `plugin_dir_url()` cannot express its own directory as a URL and every asset
 * 404s. That is a blank admin page on the screen where the user decides whether to keep the
 * migration.
 *
 * `plugin_basename()` answers correctly whenever WordPress has been told about the symlink,
 * which it is for anything in `active_plugins` — but *not* for a plugin loaded from
 * `mu-plugins`, which is exactly the situation during an import. So the answer is checked
 * against the filesystem, and when it does not hold up the plugins directory is searched for
 * the entry that resolves to this one.
 *
 * @return string
 */
function nfd_sm_plugin_basename() {
	static $basename = null;

	if ( null !== $basename ) {
		return $basename;
	}

	$file  = nfd_sm_plugin_file();
	$guess = plugin_basename( $file );

	if ( file_exists( WP_PLUGIN_DIR . '/' . $guess ) ) {
		$basename = $guess;

		return $basename;
	}

	$basename = basename( dirname( $file ) ) . '/' . basename( $file );
	$real     = realpath( dirname( $file ) );
	$entries  = is_dir( WP_PLUGIN_DIR ) ? scandir( WP_PLUGIN_DIR ) : array();

	foreach ( (array) $entries as $entry ) {
		if ( '.' === $entry || '..' === $entry || ! is_dir( WP_PLUGIN_DIR . '/' . $entry ) ) {
			continue;
		}

		if ( false !== $real && realpath( WP_PLUGIN_DIR . '/' . $entry ) === $real ) {
			$basename = $entry . '/' . basename( $file );

			break;
		}
	}

	return $basename;
}

/**
 * URL for a file inside this plugin's directory.
 *
 * Worked out when it is asked for, from the path WordPress addresses this plugin by — never
 * baked into a constant as the plugin loads. `plugin_dir_url()` can only express a symlinked
 * plugin directory through `$wp_plugin_paths`, which `wp-settings.php` fills in as it loads the
 * *active* plugins; anything that includes this plugin earlier than that — the import's own
 * mu-plugin loader, a drop-in, `wp --require` — computes its URLs before that mapping exists
 * and gets the plugin's absolute filesystem path glued onto the plugins URL, so every asset
 * 404s and the admin page renders empty.
 *
 * Handing `plugins_url()` the path under `WP_PLUGIN_DIR` sidesteps the mapping altogether: it
 * is then a plain prefix strip, correct whoever loaded the plugin and whenever they did it.
 *
 * @param string $path Path relative to the plugin directory.
 *
 * @return string
 */
function nfd_sm_plugin_url( $path = '' ) {
	return plugins_url(
		ltrim( (string) $path, '/' ),
		rtrim( WP_PLUGIN_DIR, '/\\' ) . '/' . nfd_sm_plugin_basename()
	);
}

/**
 * This plugin's directory name inside the plugins directory.
 *
 * @return string
 */
function nfd_sm_plugin_dirname() {
	$basename = nfd_sm_plugin_basename();
	$slash    = strpos( $basename, '/' );

	return false === $slash ? $basename : substr( $basename, 0, $slash );
}
